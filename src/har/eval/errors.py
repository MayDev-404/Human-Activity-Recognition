ANALYSIS_DIR = RESULTS_ROOT / "analysis"
CELL_THRESHOLD = 0.02   # a confusion cell counts for a model at >= 2% of the true class's test windows
DYNAMIC = ("WALKING", "WALKING_UPSTAIRS", "WALKING_DOWNSTAIRS")
STATIC = ("SITTING", "STANDING", "LAYING")
SIT, STAND, LAY = (ACTIVITY_NAMES.index(name) for name in ("SITTING", "STANDING", "LAYING"))
ERROR_KEYS = ("total_errors", "sitting_standing", "walking", "dynamic_static", "laying")
GENERATED = "<!-- Generated by scripts/error_analysis.py from the run folders tagged final. Do not edit by hand. -->"


@dataclass
class FinalPredictions:
    """Test predictions of the final runs, models in report order and seeds ascending.

    ``y_true`` is ``(N,)``; per model, ``y_pred`` is ``(S, N)`` and ``confusion`` ``(S, C, C)``
    with one row per seed; ``per_class`` holds each seed's ``metrics.json`` ``test.per_class``.
    """
    models: list[str]
    seeds: list[int]
    y_true: np.ndarray
    y_pred: dict[str, np.ndarray]
    confusion: dict[str, np.ndarray]
    per_class: dict[str, list[dict]]
    run_ids: dict[str, list[str]]


def read_predictions(path: Path) -> tuple[np.ndarray, np.ndarray]:
    """``(y_true, y_pred)`` int64 ``(N,)`` from a ``predictions_<split>.csv``; its index must run 0..N-1."""
    with Path(path).open(encoding="utf-8", newline="") as f:
        rows = list(csv.DictReader(f))
    index = [int(r["index"]) for r in rows]
    if index != list(range(len(rows))):
        raise ValueError(f"{path}: the index column must run 0..{len(rows) - 1} in order")
    return (np.array([int(r["y_true"]) for r in rows], dtype=np.int64),
            np.array([int(r["y_pred"]) for r in rows], dtype=np.int64))


def confusion_counts(y_true: np.ndarray, y_pred: np.ndarray, n_classes: int = N_CLASSES) -> np.ndarray:
    """``(C, C)`` count matrix, rows = true class (the layout of ``metrics.json`` ``confusion``)."""
    return np.bincount(n_classes * y_true + y_pred, minlength=n_classes * n_classes).reshape(n_classes, n_classes)


def load_final_predictions(results_root: Path = RESULTS_ROOT, configs_dir: Path = CONFIGS) -> FinalPredictions:
    """Read every model's final runs and check that they can be compared window by window.

    Raises ``ValueError`` when a model has no final runs (or not one per final seed), when fewer
    than two models exist, when runs disagree on the test labels or their order, or when a
    ``predictions_test.csv`` does not reproduce the test confusion matrix in its ``metrics.json``.
    """
    checked, missing = checked_final_runs(results_root, configs_dir)
    if missing:
        raise ValueError(f"the error analysis needs final runs for every model; none yet for {missing}")
    if len(checked) < 2:
        raise ValueError("the error overlap needs at least two models with final runs")
    models = list(checked)
    seeds = [m["seed"] for _, m in checked[models[0]]]
    y_true = None
    y_pred, confusion, per_class, run_ids = {}, {}, {}, {}
    for model, runs in checked.items():
        preds, cms = [], []
        for run_dir, m in runs:
            labels, pred = read_predictions(run_dir / "predictions_test.csv")
            if y_true is None:
                y_true = labels
            elif not np.array_equal(labels, y_true):
                raise ValueError(f"{model}/{run_dir.name}: test labels differ from the other runs; every run "
                                 "must predict the same test windows in the same order")
            cm = confusion_counts(labels, pred)
            if cm.tolist() != m["test"]["confusion"]:
                raise ValueError(f"{model}/{run_dir.name}: predictions_test.csv does not reproduce the test "
                                 "confusion matrix in metrics.json")
            preds.append(pred)
            cms.append(cm)
        y_pred[model], confusion[model] = np.stack(preds), np.stack(cms)
        per_class[model] = [m["test"]["per_class"] for _, m in runs]
        run_ids[model] = [m["run_id"] for _, m in runs]
    return FinalPredictions(models, seeds, y_true, y_pred, confusion, per_class, run_ids)


def _stats(values) -> dict[str, float | None]:
    """``{"mean", "std"}`` (sample std, None for one value) as plain floats."""
    mean, std = mean_std([float(v) for v in values])
    return {"mean": mean, "std": std}


def _ratio(numerator: float, denominator: float) -> float | None:
    return numerator / denominator if denominator else None


def per_class_f1(data: FinalPredictions) -> dict[str, dict[str, dict[str, float | None]]]:
    """Model -> class -> test F1 ``{"mean", "std"}`` over the seeds (from ``metrics.json``)."""
    return {model: {name: _stats(pc[name]["f1"] for pc in data.per_class[model]) for name in ACTIVITY_NAMES}
            for model in data.models}


def error_counts(cm: np.ndarray) -> dict[str, int]:
    """Error counts of one ``(C, C)`` test confusion matrix (rows = true class).

    ``total_errors`` (all off-diagonal windows), ``sitting_standing`` (SITTING as STANDING plus
    STANDING as SITTING), ``walking`` (one walking class as another), ``dynamic_static`` (a
    walking class as a static one or the reverse) and ``laying`` (LAYING windows predicted as
    anything else).
    """
    off = np.array(cm, dtype=np.int64)
    np.fill_diagonal(off, 0)
    dynamic = [ACTIVITY_NAMES.index(name) for name in DYNAMIC]
    static = [ACTIVITY_NAMES.index(name) for name in STATIC]
    return {
        "total_errors": int(off.sum()),
        "sitting_standing": int(off[SIT, STAND] + off[STAND, SIT]),
        "walking": int(off[np.ix_(dynamic, dynamic)].sum()),
        "dynamic_static": int(off[np.ix_(dynamic, static)].sum() + off[np.ix_(static, dynamic)].sum()),
        "laying": int(off[LAY].sum()),
    }


def error_structure(data: FinalPredictions) -> dict[str, dict]:
    """Model -> each ``error_counts`` key as ``{"mean", "std"}`` over the seeds, plus:

    - ``sitting_standing_share``: mean SITTING<->STANDING errors / mean total errors;
    - ``laying_main_target``: the class LAYING windows are most often predicted as (summed over
      the seeds; None without LAYING errors) and ``laying_main_target_share``, its share of them.
    """
    out = {}
    for model in data.models:
        per_seed = [error_counts(cm) for cm in data.confusion[model]]
        row: dict = {key: _stats(c[key] for c in per_seed) for key in ERROR_KEYS}
        row["sitting_standing_share"] = _ratio(row["sitting_standing"]["mean"], row["total_errors"]["mean"])
        laying = data.confusion[model][:, LAY].sum(axis=0)
        laying[LAY] = 0
        target = int(np.argmax(laying)) if laying.sum() else None
        row["laying_main_target"] = None if target is None else ACTIVITY_NAMES[target]
        row["laying_main_target_share"] = None if target is None else float(laying[target] / laying.sum())
        out[model] = row
    return out


def chance_jaccard(rate_a: float, rate_b: float) -> float:
    """Jaccard overlap expected if two models with error rates ``rate_a`` and ``rate_b`` erred on
    windows independently: ``ab / (a + b - ab)`` (ratio of the expected counts; 1.0 if neither errs)."""
    union = rate_a + rate_b - rate_a * rate_b
    return rate_a * rate_b / union if union else 1.0


def error_overlap(data: FinalPredictions) -> dict:
    """Overlap of the misclassified test windows between models, per seed, averaged over seeds.

    Seeds are paired across models (seed 42 of one model with seed 42 of another). Returns:

    - ``jaccard``: model -> model -> mean Jaccard ``|A & B| / |A | B|`` (1.0 on the diagonal);
    - ``pairs``: one entry per model pair, highest mean Jaccard first, with ``jaccard`` (mean),
      ``jaccard_std`` and ``jaccard_chance`` (mean of ``chance_jaccard`` over the seeds);
    - ``jaccard_mean``: mean over all pairs; ``jaccard_chance_mean``: the same for the chance values;
    - ``all_wrong``, ``exactly_one``, ``none`` and ``any_wrong``: windows misclassified by every
      model, by exactly one, by none and by at least one, ``{"mean", "std"}`` over the seeds;
    - ``exactly_one_by_model``: of the ``exactly_one`` windows, how many belong to each model;
    - ``all_wrong_by_class``: the ``all_wrong`` windows by true class;
    - ``all_wrong_sitting_standing_share``: share of the ``all_wrong`` windows that are SITTING or
      STANDING (mean count / mean count; None if no window is wrong for every model).
    """
    models, n_models = data.models, len(data.models)
    wrong = np.stack([data.y_pred[m] != data.y_true for m in models])       # (M, S, N)
    jaccard = {a: {b: 1.0 for b in models} for a in models}
    pairs = []
    for (i, a), (j, b) in itertools.combinations(enumerate(models), 2):
        inter = (wrong[i] & wrong[j]).sum(axis=1)
        union = (wrong[i] | wrong[j]).sum(axis=1)
        per_seed = np.divide(inter, union, out=np.ones(len(data.seeds)), where=union > 0)
        chance = [chance_jaccard(float(ra), float(rb)) for ra, rb in zip(wrong[i].mean(axis=1), wrong[j].mean(axis=1))]
        stats = _stats(per_seed)
        jaccard[a][b] = jaccard[b][a] = stats["mean"]
        pairs.append({"models": [a, b], "jaccard": stats["mean"], "jaccard_std": stats["std"],
                      "jaccard_chance": float(np.mean(chance))})
    pairs.sort(key=lambda p: -p["jaccard"])

    n_wrong = wrong.sum(axis=0)                                              # (S, N)
    all_wrong = n_wrong == n_models
    static_postures = np.isin(data.y_true, [SIT, STAND])
    out = {
        "jaccard": jaccard,
        "pairs": pairs,
        "jaccard_mean": float(np.mean([p["jaccard"] for p in pairs])),
        "jaccard_chance_mean": float(np.mean([p["jaccard_chance"] for p in pairs])),
        "all_wrong": _stats(all_wrong.sum(axis=1)),
        "exactly_one": _stats((n_wrong == 1).sum(axis=1)),
        "none": _stats((n_wrong == 0).sum(axis=1)),
        "any_wrong": _stats((n_wrong > 0).sum(axis=1)),
        "exactly_one_by_model": {m: _stats(((n_wrong == 1) & wrong[i]).sum(axis=1)) for i, m in enumerate(models)},
        "all_wrong_by_class": {name: _stats((all_wrong & (data.y_true == c)).sum(axis=1))
                               for c, name in enumerate(ACTIVITY_NAMES)},
    }
    out["all_wrong_sitting_standing_share"] = _ratio(float((all_wrong & static_postures).sum(axis=1).mean()),
                                                     out["all_wrong"]["mean"])
    return out


def confusion_cells(data: FinalPredictions, threshold: float = CELL_THRESHOLD) -> dict:
    """Off-diagonal confusion cells (true -> predicted) that hold at least ``threshold`` of the true
    class's test windows (confusions summed over the seeds) for at least one model.

    A cell is ``shared`` when every model reaches the threshold, ``model_specific`` when one or two
    models do (and not all), and ``partly_shared`` otherwise. Each entry has ``cell``
    (``"TRUE->PRED"``), ``true``, ``pred``, ``models`` (those at or above the threshold) and
    ``share`` (model -> fraction of the true class's windows); entries are sorted by their mean share.
    """
    summed = {m: data.confusion[m].sum(axis=0) for m in data.models}
    groups: dict[str, list[dict]] = {"shared": [], "model_specific": [], "partly_shared": []}
    for i, j in itertools.permutations(range(N_CLASSES), 2):
        share = {m: float(_ratio(summed[m][i, j], summed[m][i].sum()) or 0.0) for m in data.models}
        above = [m for m in data.models if share[m] >= threshold]
        if not above:
            continue
        kind = ("shared" if len(above) == len(data.models) else
                "model_specific" if len(above) <= 2 else "partly_shared")
        groups[kind].append({"cell": f"{ACTIVITY_NAMES[i]}->{ACTIVITY_NAMES[j]}", "true": ACTIVITY_NAMES[i],
                             "pred": ACTIVITY_NAMES[j], "models": above, "share": share})
    for entries in groups.values():
        entries.sort(key=lambda e: -float(np.mean(list(e["share"].values()))))
    return {"threshold": threshold, **groups, **{f"n_{kind}": len(entries) for kind, entries in groups.items()}}


def analyse(data: FinalPredictions, threshold: float = CELL_THRESHOLD) -> dict:
    """The full error summary (the content of ``error_summary.json``)."""
    return {
        "models": data.models,
        "seeds": data.seeds,
        "n_test_windows": int(len(data.y_true)),
        "run_ids": data.run_ids,
        "per_class_f1": per_class_f1(data),
        "error_structure": error_structure(data),
        "overlap": error_overlap(data),
        "confusion_cells": confusion_cells(data, threshold),
    }


# ---- formatting and files


def _pm(stats: dict, spec: str) -> str:
    """``0.941 ± 0.004``; the mean alone without a std."""
    text = format(stats["mean"], spec)
    return text if stats["std"] is None else f"{text} ± {format(stats['std'], spec)}"


def _pct(value: float | None) -> str:
    return "n/a" if value is None else f"{100 * value:.1f}%"


def _seeds_text(summary: dict) -> str:
    return ", ".join(map(str, summary["seeds"]))


def _write_csv(rows: list[dict], path: Path) -> Path:
    path.parent.mkdir(parents=True, exist_ok=True)
    with path.open("w", encoding="utf-8", newline="") as f:
        writer = csv.DictWriter(f, fieldnames=list(rows[0]))
        writer.writeheader()
        writer.writerows({k: ("" if v is None else v) for k, v in row.items()} for row in rows)
    return path


def per_class_rows(summary: dict) -> list[dict]:
    """Wide ``per_class_f1.csv`` rows: ``class``, then ``<model>_mean`` and ``<model>_std`` per model."""
    table = summary["per_class_f1"]
    return [{"class": name, **{f"{m}_{stat}": table[m][name][stat] for m in summary["models"] for stat in ("mean", "std")}}
            for name in ACTIVITY_NAMES]


def render_per_class_md(summary: dict) -> str:
    models, table = summary["models"], summary["per_class_f1"]
    lines = [GENERATED,
             f"Test F1 per class: mean ± sample std over seeds {_seeds_text(summary)} of each model's final runs.",
             "", "| Class | " + " | ".join(models) + " |", "|" + "---|" * (len(models) + 1)]
    lines += [f"| {name} | " + " | ".join(_pm(table[m][name], ".3f") for m in models) + " |" for name in ACTIVITY_NAMES]
    return "\n".join(lines) + "\n"


def error_structure_rows(summary: dict) -> list[dict]:
    """``error_structure.csv`` rows: per model the mean and std of each error count, then the shares."""
    rows = []
    for model, s in summary["error_structure"].items():
        row: dict = {"model": model}
        for key in ERROR_KEYS:
            row[f"{key}_mean"], row[f"{key}_std"] = s[key]["mean"], s[key]["std"]
        row.update(sitting_standing_share=s["sitting_standing_share"], laying_main_target=s["laying_main_target"],
                   laying_main_target_share=s["laying_main_target_share"])
        rows.append(row)
    return rows


def render_error_structure_md(summary: dict) -> str:
    lines = [GENERATED,
             f"Test errors per model: mean ± sample std over seeds {_seeds_text(summary)} "
             f"({summary['n_test_windows']:,} test windows per run).",
             "",
             "| Model | Test errors | Sitting↔Standing | Share of errors | Among walking classes | "
             "Dynamic↔static | Laying errors | Laying main target |",
             "|" + "---|" * 8]
    for model, s in summary["error_structure"].items():
        target = s["laying_main_target"]
        target_text = "n/a" if target is None else f"{display_name(target)} ({_pct(s['laying_main_target_share'])})"
        lines.append(f"| {model} | {_pm(s['total_errors'], '.1f')} | {_pm(s['sitting_standing'], '.1f')} | "
                     f"{_pct(s['sitting_standing_share'])} | {_pm(s['walking'], '.1f')} | "
                     f"{_pm(s['dynamic_static'], '.1f')} | {_pm(s['laying'], '.1f')} | {target_text} |")
    lines += ["",
              "Sitting↔Standing counts SITTING predicted as STANDING plus the reverse; its share is mean "
              "Sitting↔Standing errors over mean test errors. Among walking classes counts one walking class "
              "predicted as another. Dynamic↔static counts a walking class predicted as SITTING, STANDING or "
              "LAYING, or the reverse. Laying main target is the class LAYING windows are most often predicted "
              "as (summed over the seeds) and its share of the LAYING errors."]
    return "\n".join(lines) + "\n"


def overlap_rows(summary: dict) -> list[dict]:
    """``error_overlap.csv``: the mean Jaccard matrix, one row per model."""
    jaccard = summary["overlap"]["jaccard"]
    return [{"model": a, **{b: jaccard[a][b] for b in summary["models"]}} for a in summary["models"]]


def render_summary_md(summary: dict) -> str:
    models, ov, cells = summary["models"], summary["overlap"], summary["confusion_cells"]
    n_models = len(models)
    lines = [GENERATED, "# Error analysis of the final runs", "",
             f"Models: {', '.join(models)}. Seeds {_seeds_text(summary)}, paired across models. "
             f"{summary['n_test_windows']:,} test windows per run. Counts are mean ± sample std over the seeds. "
             "Per-class F1 is in per_class_f1.md and the error structure in error_structure.md; every number "
             "here is also in error_summary.json.", "",
             "## Error overlap", "",
             "Jaccard overlap of the misclassified test windows (|A ∩ B| / |A ∪ B|), computed per seed and "
             "averaged over the seeds:", "",
             "| | " + " | ".join(models) + " |", "|" + "---|" * (n_models + 1)]
    lines += [f"| {a} | " + " | ".join("" if a == b else f"{ov['jaccard'][a][b]:.3f}" for b in models) + " |"
              for a in models]
    lines += ["", "Model pairs, highest overlap first. Chance is the Jaccard expected if the two models erred on "
              "windows independently at their own error rates.", "",
              "| Pair | Jaccard | Chance |", "|---|---|---|"]
    lines += [f"| {p['models'][0]} / {p['models'][1]} | {_pm({'mean': p['jaccard'], 'std': p['jaccard_std']}, '.3f')} | "
              f"{p['jaccard_chance']:.3f} |" for p in ov["pairs"]]
    lines += ["", f"Mean over all pairs: Jaccard {ov['jaccard_mean']:.3f}, chance {ov['jaccard_chance_mean']:.3f}.",
              "", "| Test windows | Count |", "|---|---|",
              f"| Misclassified by all {n_models} models | {_pm(ov['all_wrong'], '.1f')} |",
              f"| Misclassified by exactly one model | {_pm(ov['exactly_one'], '.1f')} |",
              f"| Misclassified by at least one model | {_pm(ov['any_wrong'], '.1f')} |",
              f"| Misclassified by none | {_pm(ov['none'], '.1f')} |",
              "", "Windows misclassified by exactly one model, by model: "
              + "; ".join(f"{m} {_pm(s, '.1f')}" for m, s in ov["exactly_one_by_model"].items()) + ".",
              "", f"Windows misclassified by all {n_models} models, by true class: "
              + "; ".join(f"{display_name(c)} {_pm(s, '.1f')}" for c, s in ov["all_wrong_by_class"].items())
              + f". Sitting or Standing: {_pct(ov['all_wrong_sitting_standing_share'])} of them.",
              "", "## Shared and model-specific confusions", "",
              f"A confusion cell (true → predicted) counts for a model when it holds at least "
              f"{100 * cells['threshold']:.0f}% of that class's test windows (summed over the seeds). Shared: every "
              "model; model-specific: one or two models; partly shared: the rest.", ""]
    for kind, title in (("shared", "Shared"), ("model_specific", "Model-specific"), ("partly_shared", "Partly shared")):
        entries = cells[kind]
        lines.append(f"**{title} ({len(entries)})**" + ("" if entries else ": none."))
        lines += [f"- {display_name(e['true'])} → {display_name(e['pred'])}: "
                  + ", ".join(f"{m} {_pct(e['share'][m])}" for m in e["models"]) for e in entries]
        lines.append("")
    return "\n".join(lines)


def plot_per_class_f1(summary: dict, path: Path, slots: dict[str, int] | None = None) -> Path:
    """Grouped bars of test F1 per class (groups) and model (bars), mean with ± std error bars.

    Bars start at zero; ``slots`` fixes each model's palette slot (default: summary order). Returns ``path``.
    """
    models, table = summary["models"], summary["per_class_f1"]
    slots = slots if slots is not None else {m: i for i, m in enumerate(models)}
    width = 0.8 / len(models)
    x = np.arange(len(ACTIVITY_NAMES))
    fig = Figure(figsize=(4.6, 2.8), facecolor=SURFACE, layout="constrained")
    ax = fig.subplots()
    _style_axes(ax)
    for k, model in enumerate(models):
        means = [table[model][c]["mean"] for c in ACTIVITY_NAMES]
        stds = [table[model][c]["std"] or 0.0 for c in ACTIVITY_NAMES]
        offsets = x - 0.4 + width * (k + 0.5)
        # Surface-coloured edges give the gap between neighbouring bars.
        ax.bar(offsets, means, width, color=CATEGORICAL[slots[model]], edgecolor=SURFACE, linewidth=0.6,
               label=model, zorder=2)
        ax.errorbar(offsets, means, yerr=stds, fmt="none", ecolor=INK_SECONDARY, elinewidth=0.6, capsize=1.2,
                    capthick=0.6, zorder=3)
    ax.set_xticks(x, [display_name(c).replace(" ", "\n") for c in ACTIVITY_NAMES])
    ax.set_ylim(0, 1.05)
    ax.set_yticks(np.linspace(0, 1, 6))
    ax.set_ylabel("Test F1 (mean ± std over seeds)", fontsize=7, color=INK_SECONDARY)
    fig.legend(fontsize=6.5, frameon=False, loc="outside upper center", ncol=min(len(models), 5),
               labelcolor=INK_SECONDARY, handlelength=1.0)
    return _save(fig, path)


def plot_error_overlap(summary: dict, path: Path) -> Path:
    """Heatmap of the mean pairwise Jaccard overlap of misclassified test windows, labelled per cell.

    Colour runs from 0 to 1 on the blue sequential ramp; the diagonal (a model with itself) is a
    neutral cell without a label. Returns ``path``.
    """
    models = summary["models"]
    n = len(models)
    values = np.array([[summary["overlap"]["jaccard"][a][b] for b in models] for a in models])
    shade = np.ma.masked_array(values, mask=np.eye(n, dtype=bool))
    fig = Figure(figsize=(3.4, 3.0), facecolor=SURFACE, layout="constrained")
    ax = fig.subplots()
    ax.set_facecolor(SURFACE)
    ax.pcolormesh(shade, cmap=SEQUENTIAL, vmin=0.0, vmax=1.0, edgecolors=SURFACE, linewidth=1.5)
    for i in range(n):
        ax.add_patch(Rectangle((i, i), 1, 1, facecolor=GRID, edgecolor=SURFACE, linewidth=1.5))
        for j in range(n):
            if i != j:
                ink = "#ffffff" if values[i, j] > 0.55 else INK
                ax.text(j + 0.5, i + 0.5, f"{values[i, j]:.2f}", ha="center", va="center", fontsize=6, color=ink)
    ax.set_xticks(np.arange(n) + 0.5, models, rotation=35, ha="right", rotation_mode="anchor")
    ax.set_yticks(np.arange(n) + 0.5, models)
    ax.set_xlim(0, n)
    ax.set_ylim(n, 0)
    ax.set_aspect("equal")
    for side in ax.spines.values():
        side.set_visible(False)
    ax.tick_params(length=0, labelsize=6.5, labelcolor=INK_SECONDARY)
    return _save(fig, path)


def write_error_analysis(results_root: Path = RESULTS_ROOT, configs_dir: Path = CONFIGS,
                         out_dir: Path | None = None, threshold: float = CELL_THRESHOLD) -> list[Path]:
    """Run the analysis on the final runs and write every output file into ``out_dir``
    (default ``<results_root>/analysis``). Returns the written paths."""
    out_dir = Path(out_dir) if out_dir is not None else Path(results_root) / "analysis"
    out_dir.mkdir(parents=True, exist_ok=True)
    summary = analyse(load_final_predictions(results_root, configs_dir), threshold)
    all_models = list(model_configs(configs_dir))
    slots = {m: all_models.index(m) for m in summary["models"]}

    paths = [_write_csv(per_class_rows(summary), out_dir / "per_class_f1.csv")]
    texts = {"per_class_f1.md": render_per_class_md(summary),
             "error_structure.md": render_error_structure_md(summary),
             "error_summary.md": render_summary_md(summary),
             "error_summary.json": json.dumps(summary, indent=2, ensure_ascii=False) + "\n"}
    paths.append(_write_csv(error_structure_rows(summary), out_dir / "error_structure.csv"))
    paths.append(_write_csv(overlap_rows(summary), out_dir / "error_overlap.csv"))
    for name, text in texts.items():
        (out_dir / name).write_text(text, encoding="utf-8")
        paths.append(out_dir / name)
    paths.append(plot_per_class_f1(summary, out_dir / "per_class_f1.png", slots))
    paths.append(plot_error_overlap(summary, out_dir / "error_overlap.png"))
    return paths

"""Error analysis of the final runs (PHASE3_SPEC section 5, F3.2).

Inputs are the run folders tagged ``final`` (one per model and final seed): the test confusion
matrices in ``metrics.json`` and the per-window ``predictions_test.csv``. These are the selected
checkpoints evaluated once on the test split, so nothing here feeds back into any model or run
choice. Outputs in ``results/analysis/``:

- ``per_class_f1.csv``/``.md`` and ``per_class_f1.png``: test F1 per class and model, mean and
  sample std over the seeds.
- ``error_structure.csv``/``.md``: per model (mean over seeds) the total test errors,
  SITTING<->STANDING errors and their share, errors among the walking classes, dynamic<->static
  errors, and LAYING errors with their main target class.
- ``error_overlap.csv`` and ``error_overlap.png``: pairwise Jaccard overlap of the misclassified
  test windows, computed per seed and averaged over seeds.
- ``error_summary.json``/``.md``: every number above under stable keys (read by the Part C
  builder's ``{{analysis:<dotted.key>}}`` placeholders), plus the windows misclassified by all,
  exactly one and none of the models, and the shared and model-specific confusion cells.
"""


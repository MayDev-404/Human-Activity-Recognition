"""GRU versus BiLSTM CPU latency check (PHASE3_SPEC F3.3).

The single-process profile (``results/profile_rtx4060-laptop.csv``) has the final GRU much slower
than the final BiLSTM at batch size 1 on one CPU thread, although the GRU has fewer parameters.
On CPU, PyTorch can run ``nn.LSTM`` through oneDNN (``torch.backends.mkldnn``). This check times
both final configs in one process with oneDNN enabled (the PyTorch default) and disabled, so
whether that path explains the gap is decided by measurement. Outputs in ``results/analysis/``:
``gru_latency_check.csv`` (every measurement) and ``gru_latency_check.md`` (the summary; the
report may quote numbers from this check only from that file).
"""

from __future__ import annotations

import csv
import statistics
import warnings
from pathlib import Path

import torch

from har.eval.profiling import count_params, hardware_info, measure_latency
from har.eval.results import INPUT_SHAPES, PROFILE_LABEL, _config_label, final_configs, profile_latencies
from har.utils.build import build_from_target
from har.utils.config import load_config, load_yaml
from har.utils.paths import CONFIGS, RESULTS_ROOT
from har.utils.seed import set_seed

MODELS = ("bilstm", "gru")
REPEATS = 3


def measure_onednn_effect(models: tuple[str, ...] = MODELS, configs_dir: Path = CONFIGS,
                          repeats: int = REPEATS) -> list[dict]:
    """CPU latency at batch size 1 of each model's final config with oneDNN enabled and disabled.

    Each model is built once from ``configs/final/<name>.yaml`` (``configs/<name>.yaml`` when there
    is none) with its seed. Within each of ``repeats`` rounds every model is timed with oneDNN on,
    then off, using the warmup, iteration and thread settings of ``base.yaml`` ``eval``, so slow
    drift affects both conditions alike. The global oneDNN flag is restored after each measurement.
    Returns one row per measurement: ``model``, ``config``, ``params``, ``onednn``, ``repeat``,
    ``mean_ms``, ``p50_ms``, ``p95_ms``, ``threads``, ``warmup``, ``iters``.
    """
    base = Path(configs_dir) / "base.yaml"
    ev = load_yaml(base)["eval"]
    configs = final_configs(configs_dir)
    built = {}
    for name in models:
        cfg = load_config(configs[name], base_cfg=base)
        set_seed(cfg["seed"])
        model = build_from_target(cfg["model"]["target"], cfg["model"].get("params") or {})
        built[name] = (configs[name], model, INPUT_SHAPES[cfg["data"]["representation"]])
    rows = []
    for repeat in range(1, repeats + 1):
        for name, (path, model, shape) in built.items():
            for enabled in (True, False):
                with warnings.catch_warnings():
                    # flags() also sets oneDNN TF32 on entry and exit, which warns about Intel GPUs; irrelevant on CPU.
                    warnings.filterwarnings("ignore", message="TF32 acceleration on top of oneDNN")
                    with torch.backends.mkldnn.flags(enabled=enabled):
                        lat = measure_latency(model, shape, "cpu", batch_size=1, warmup=ev["latency_warmup"],
                                              iters=ev["latency_iters"], threads=ev["latency_threads"])
                rows.append({"model": name, "config": _config_label(path), "params": count_params(model),
                             "onednn": enabled, "repeat": repeat, "mean_ms": lat["mean_ms"], "p50_ms": lat["p50_ms"],
                             "p95_ms": lat["p95_ms"], "threads": lat["threads"], "warmup": lat["warmup"],
                             "iters": lat["iters"]})
    return rows


def summarise(rows: list[dict]) -> dict[str, dict]:
    """Model -> ``params``, ``onednn_on_ms`` and ``onednn_off_ms`` (median over the repeats of each
    repeat's mean latency) and ``off_over_on`` (their ratio)."""
    out = {}
    for name in dict.fromkeys(r["model"] for r in rows):
        own = [r for r in rows if r["model"] == name]
        on = statistics.median(r["mean_ms"] for r in own if r["onednn"])
        off = statistics.median(r["mean_ms"] for r in own if not r["onednn"])
        out[name] = {"params": own[0]["params"], "onednn_on_ms": on, "onednn_off_ms": off, "off_over_on": off / on}
    return out


def render_latency_check_md(rows: list[dict], profile: dict[str, float], hw: dict,
                            profile_label: str = PROFILE_LABEL) -> str:
    """The summary file: settings, the table, the GRU/BiLSTM ratios and the single-process profile values."""
    summary = summarise(rows)
    first = rows[0]
    repeats = max(r["repeat"] for r in rows)
    configs = ", ".join(dict.fromkeys(r["config"] for r in rows))
    lines = [
        "<!-- Generated by scripts/gru_latency_check.py. Do not edit by hand. -->",
        "# GRU latency check (F3.3)", "",
        f"CPU latency at batch size 1 on {first['threads']} thread of the final configs ({configs}), measured in "
        "one process with oneDNN (`torch.backends.mkldnn`) enabled, the PyTorch default, and disabled. Each value "
        f"is the median over {repeats} repeats of the mean of {first['iters']} timed forward passes after "
        f"{first['warmup']} warm-up passes; within each repeat both conditions are measured for each model in turn.",
        "",
        f"Environment: torch {hw['torch']}, oneDNN available: {torch.backends.mkldnn.is_available()}, "
        f"CPU {hw['cpu']}, {hw['os']}.",
        "",
        "| Model | Params | oneDNN enabled (ms) | oneDNN disabled (ms) | Disabled / enabled |",
        "|---|---|---|---|---|",
    ]
    lines += [f"| {name} | {s['params']:,} | {s['onednn_on_ms']:.3f} | {s['onednn_off_ms']:.3f} | "
              f"{s['off_over_on']:.2f} |" for name, s in summary.items()]
    if "gru" in summary and "bilstm" in summary:
        gru, lstm = summary["gru"], summary["bilstm"]
        lines += ["", f"GRU / BiLSTM latency: {gru['onednn_on_ms'] / lstm['onednn_on_ms']:.2f} with oneDNN enabled, "
                      f"{gru['onednn_off_ms'] / lstm['onednn_off_ms']:.2f} with oneDNN disabled."]
    known = {name: profile[name] for name in summary if name in profile}
    if known:
        lines += ["", f"For reference, results/profile_{profile_label}.csv (single process, oneDNN enabled) has "
                      + ", ".join(f"{name} {ms:.3f} ms" for name, ms in known.items()) + "."]
    lines += ["", "Every measurement is in gru_latency_check.csv."]
    return "\n".join(lines) + "\n"


def write_latency_check(configs_dir: Path = CONFIGS, out_dir: Path | None = None, results_root: Path = RESULTS_ROOT,
                        repeats: int = REPEATS, profile_label: str = PROFILE_LABEL) -> list[Path]:
    """Measure, then write ``gru_latency_check.csv`` and ``.md`` into ``out_dir``
    (default ``<results_root>/analysis``). Returns both paths."""
    out_dir = Path(out_dir) if out_dir is not None else Path(results_root) / "analysis"
    out_dir.mkdir(parents=True, exist_ok=True)
    rows = measure_onednn_effect(MODELS, configs_dir, repeats)
    csv_path = out_dir / "gru_latency_check.csv"
    with csv_path.open("w", encoding="utf-8", newline="") as f:
        writer = csv.DictWriter(f, fieldnames=list(rows[0]))
        writer.writeheader()
        writer.writerows({k: str(v).lower() if isinstance(v, bool) else v for k, v in row.items()} for row in rows)
    profile = profile_latencies(Path(results_root) / f"profile_{profile_label}.csv")
    md_path = out_dir / "gru_latency_check.md"
    md_path.write_text(render_latency_check_md(rows, profile, hardware_info("cpu"), profile_label), encoding="utf-8")
    return [csv_path, md_path]
